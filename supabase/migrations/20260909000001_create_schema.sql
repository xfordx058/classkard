create index if not exists idx_students_user on public.students(user_id);
create index if not exists idx_enrollments_section on public.enrollments(section_id);
create index if not exists idx_enrollments_student on public.enrollments(student_id);
create index if not exists idx_records_student on public.records(student_id);
create index if not exists idx_records_section on public.records(section_id);